function dlBlob(blob: Blob, name: string) {
  const u = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = u;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(u);
}
function dlStr(
  content: string,
  name: string,
  mime = "text/plain;charset=utf-8",
) {
  dlBlob(new Blob([content], { type: mime }), name);
}

function detectSqlType(rows: Record<string, unknown>[], col: string): string {
  const vals = rows
    .slice(0, 100)
    .map((r) => r[col])
    .filter((v) => v != null && v !== "");
  if (vals.length === 0) return "TEXT";
  const allNum = vals.every((v) => !Number.isNaN(Number(v)));
  const allBool = vals.every(
    (v) =>
      String(v).toLowerCase() === "true" ||
      String(v).toLowerCase() === "false" ||
      String(v) === "1" ||
      String(v) === "0",
  );
  const allDate = vals.every((v) => !Number.isNaN(Date.parse(String(v))));
  if (allBool) return "BOOLEAN";
  if (allDate) return "TIMESTAMP";
  if (allNum) return "NUMERIC(18,4)";
  return "VARCHAR(255)";
}

function makeCreateTable(
  name: string,
  headers: string[],
  rows: Record<string, unknown>[],
): string {
  let sql = `-- Auto-generated by OQZARO SQL Designer\n`;
  sql += `IF OBJECT_ID(N'dbo.${name}', N'U') IS NOT NULL DROP TABLE dbo.${name};\nGO\n\n`;
  sql += `CREATE TABLE dbo.${name} (\n`;
  headers.forEach((h, i) => {
    const safe = h.replace(/[^\w\u0600-\u06FF]/g, "_");
    const type = detectSqlType(rows, h);
    sql += `\t[${safe}] ${type}${i < headers.length - 1 ? "," : ""}\n`;
  });
  sql += `);\nGO\n\n`;
  return sql;
}

function makeInsertSql(
  name: string,
  headers: string[],
  rows: Record<string, unknown>[],
  limit = 50,
): string {
  let sql = `INSERT INTO dbo.${name} (${headers.map((h) => `[${h.replace(/[^\w\u0600-\u06FF]/g, "_")}]`).join(", ")})\nVALUES\n`;
  const rowSqls = rows.slice(0, limit).map((r) => {
    const vals = headers.map((h) => {
      const v = r[h];
      if (v == null || v === "") return "NULL";
      if (!Number.isNaN(Number(v))) return String(v);
      return `N'${String(v).replace(/'/g, "''")}'`;
    });
    return `\t(${vals.join(", ")})`;
  });
  sql += rowSqls.join(",\n") + ";";
  return sql;
}

