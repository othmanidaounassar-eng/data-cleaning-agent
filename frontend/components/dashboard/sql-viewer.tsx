const NUMBER_RE = /\b\d+(?:\.\d+)?\b/;

/* ─── SQL Syntax Highlighter ─── */
function highlightSql(sql: string): React.ReactNode[] {
  const tokens: React.ReactNode[] = [];
  let rest = sql;
  let key = 0;

  // Extract comments first
  const parts: { type: "comment" | "code"; text: string }[] = [];
  let lastIdx = 0;
  const commentRegex = /(--[^\n]*|\/\*[\s\S]*?\*\/)/g;
  let m: RegExpExecArray | null;
  while ((m = commentRegex.exec(rest)) !== null) {
    if (m.index > lastIdx)
      parts.push({ type: "code", text: rest.substring(lastIdx, m.index) });
    parts.push({ type: "comment", text: m[0] });
    lastIdx = m.index + m[0].length;
  }
  if (lastIdx < rest.length)
    parts.push({ type: "code", text: rest.substring(lastIdx) });

  const codeStyle = (txt: string): React.ReactNode[] => {
    const out: React.ReactNode[] = [];
    // Split by strings and identify keywords/numbers
    const segments = txt.split(STRING_RE);
    for (let i = 0; i < segments.length; i++) {
      const seg = segments[i];
      if (!seg) continue;
      if (i % 2 === 1) {
        out.push(
          <span key={key++} className="text-emerald-300">
            "{seg}"
          </span>,
        );
        continue;
      }
      const numSegs = seg.split(NUMBER_RE);
      for (let j = 0; j < numSegs.length; j++) {
        if (!numSegs[j]) continue;
        if (j % 2 === 1) {
          out.push(
            <span key={key++} className="text-amber-300">
              {numSegs[j]}
            </span>,
          );
          continue;
        }
        const kwSegs = numSegs[j].split(KEYWORDS);
        for (let k = 0; k < kwSegs.length; k++) {
          if (!kwSegs[k]) continue;
          if (k % 2 === 1) {
            out.push(
              <span key={key++} className="text-[#4f7cff] font-semibold">
                {kwSegs[k]}
              </span>,
            );
          } else {
            out.push(<span key={key++}>{kwSegs[k]}</span>);
          }
        }
      }
    }
    return out;
  };

  for (const p of parts) {
    if (p.type === "comment") {
      tokens.push(
        <span key={key++} className="text-white/25 italic">
          {p.text}
        </span>,
      );
    } else {
      tokens.push(<span key={key++}>{codeStyle(p.text)}</span>);
    }
  }
  return tokens;
}

