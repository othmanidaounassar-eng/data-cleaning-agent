const KEYWORDS =
  /\b(SELECT|FROM|WHERE|GROUP\s+BY|ORDER\s+BY|HAVING|LIMIT|OFFSET|JOIN|LEFT|RIGHT|INNER|OUTER|ON|AS|AND|OR|NOT|IN|BETWEEN|LIKE|IS|NULL|DISTINCT|COUNT|SUM|AVG|MIN|MAX|NVL|IFNULL|COALESCE|ALTER|CREATE|DROP|INSERT|UPDATE|DELETE|TABLE|INDEX|PRIMARY|KEY|REFERENCES|CASE|WHEN|THEN|ELSE|END|UNION|ALL|EXISTS|ASC|DESC|INTO|VALUES|SET|DATABASE|USE|TRUNCATE|VIEW|INT|VARCHAR|TEXT|NUMERIC|DECIMAL|REAL|BOOLEAN|TIMESTAMP|DATE|BIGINT)\b/i;
